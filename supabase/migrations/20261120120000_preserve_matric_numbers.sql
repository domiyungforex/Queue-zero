-- Student matriculation numbers are institution-issued.
-- TuRnMaRk must not uppercase, regenerate, or replace them.
-- Attendance must not create a student. This migration does not update existing rows.
-- Do not apply to production without explicit authorization.

begin;

comment on column public.school_profiles.id is
  'Permanent internal student id. Attendance and enrollments reference this id. It is not a matriculation number.';
comment on column public.school_profiles.matric_number is
  'Institution-issued matriculation number, stored as supplied aside from surrounding whitespace. Never generated by TuRnMaRk.';

comment on index public.school_profiles_org_normalized_matric is
  'One matriculation number per organization after case and whitespace are ignored for comparison only. The stored matric_number is not rewritten to this key. Another organization may use the same number.';

create or replace function private.preserve_school_matric()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if tg_op = 'INSERT' then
    if coalesce(current_setting('turnmark.block_student_create', true), '') = 'on' then
      raise exception 'Attendance cannot create a student or assign a matriculation number' using errcode = '22023';
    end if;
    return new;
  end if;

  if new.matric_number is distinct from old.matric_number then
    if private.normalized_matric(new.matric_number) is not distinct from private.normalized_matric(old.matric_number) then
      new.matric_number := old.matric_number;
    elsif coalesce(current_setting('turnmark.allow_matric_correction', true), '') is distinct from 'on' then
      raise exception 'Institution matriculation numbers cannot be replaced automatically' using errcode = '22023';
    end if;
  end if;
  return new;
end $$;

revoke all on function private.preserve_school_matric() from public, anon, authenticated, service_role;

drop trigger if exists school_profiles_preserve_matric on public.school_profiles;
create trigger school_profiles_preserve_matric
  before insert or update of matric_number on public.school_profiles
  for each row execute function private.preserve_school_matric();

create or replace function public.school_register_student(
  p_organization_id uuid,
  p_full_name text,
  p_matric_number text,
  p_faculty_id uuid,
  p_department_id uuid,
  p_level text,
  p_email text,
  p_phone text,
  p_consent boolean,
  p_photo_path text
) returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  person uuid;
  clean_name text := btrim(p_full_name);
  clean_matric text := btrim(p_matric_number);
  clean_email text := nullif(lower(btrim(coalesce(p_email, ''))), '');
  clean_phone text := nullif(btrim(coalesce(p_phone, '')), '');
  clean_level text := btrim(p_level);
  existing_id uuid;
  existing_matric text;
begin
  if not exists (select 1 from public.businesses where id = p_organization_id and organization_mode in ('SCHOOL', 'HYBRID')) then
    return jsonb_build_object('ok', false, 'message', 'This institution is not accepting registration.');
  end if;
  if p_consent is not true then
    return jsonb_build_object('ok', false, 'message', 'Registration needs your consent to store a reference photograph.');
  end if;
  if p_photo_path is null or p_photo_path !~ ('^reference/' || p_organization_id::text || '/[0-9a-f-]{36}\.(jpg|png|webp)$') then
    return jsonb_build_object('ok', false, 'message', 'A reference photograph must be stored before the profile is created.');
  end if;
  if length(clean_name) not between 1 and 160 or length(clean_matric) not between 1 and 80 or length(clean_level) not between 1 and 40 then
    return jsonb_build_object('ok', false, 'message', 'Check the name, matriculation number and academic level.');
  end if;
  if clean_email is not null and clean_email !~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' then
    return jsonb_build_object('ok', false, 'message', 'Enter a valid email address or leave it blank.');
  end if;
  if clean_phone is not null and length(clean_phone) not between 7 and 20 then
    return jsonb_build_object('ok', false, 'message', 'Enter a valid phone number or leave it blank.');
  end if;
  if clean_email is null and clean_phone is null then
    return jsonb_build_object('ok', false, 'message', 'Add an email address or a phone number.');
  end if;
  if not exists (
    select 1 from public.departments d
    where d.id = p_department_id and d.organization_id = p_organization_id and d.faculty_id = p_faculty_id
  ) then
    return jsonb_build_object('ok', false, 'message', 'Choose a department that belongs to the selected faculty.');
  end if;

  perform pg_advisory_xact_lock(hashtextextended(p_organization_id::text || ':' || private.normalized_matric(clean_matric), 7));
  select sp.id, sp.matric_number into existing_id, existing_matric
  from public.school_profiles sp
  where sp.organization_id = p_organization_id
    and private.normalized_matric(sp.matric_number) = private.normalized_matric(clean_matric);
  if existing_id is not null then
    return jsonb_build_object(
      'ok', false,
      'code', 'DUPLICATE',
      'student_id', existing_id,
      'matric_number', existing_matric,
      'message', 'This matriculation number is already registered at this institution. The registered number was not changed.'
    );
  end if;
  if clean_email is not null and exists (select 1 from public.people where organization_id = p_organization_id and email = clean_email) then
    return jsonb_build_object('ok', false, 'message', 'That email is already used at this institution.');
  end if;

  insert into public.people (organization_id, type, full_name, email)
  values (p_organization_id, 'STUDENT', clean_name, clean_email)
  returning id into person;

  insert into public.school_profiles (
    id, organization_id, department_id, matric_number, level, phone,
    reference_photo_path, photo_enrolled_at, consent_at, consent_version
  ) values (
    person, p_organization_id, p_department_id, clean_matric, clean_level, clean_phone,
    p_photo_path, clock_timestamp(), clock_timestamp(), '2026-11-student-photo-v1'
  );

  return jsonb_build_object(
    'ok', true,
    'student_id', person,
    'matric_number', clean_matric,
    'message', 'Registration saved. Use this same matriculation number the next time you attend.'
  );
exception
  when unique_violation then
    return jsonb_build_object('ok', false, 'code', 'DUPLICATE', 'message', 'This matriculation number or email is already registered. The existing number was not changed.');
end $$;

create or replace function public.school_correct_student(p_organization_id uuid, p_payload jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare
  student uuid := (p_payload->>'student_id')::uuid;
  clean_name text := btrim(p_payload->>'full_name');
  supplied_matric text := btrim(p_payload->>'matric_number');
  clean_level text := btrim(p_payload->>'level');
  department uuid := (p_payload->>'department_id')::uuid;
  previous text;
begin
  if private.current_clerk_user_id() is null or not private.school_manager(p_organization_id) then
    raise exception 'Not authorized' using errcode = '42501';
  end if;
  if length(clean_name) not between 1 and 160 or length(supplied_matric) not between 1 and 80 or length(clean_level) not between 1 and 40 then
    return jsonb_build_object('ok', false, 'message', 'Check the name, matriculation number and level.');
  end if;
  if not exists (select 1 from public.departments where id = department and organization_id = p_organization_id) then
    return jsonb_build_object('ok', false, 'message', 'Choose a department in this institution.');
  end if;
  select matric_number into previous from public.school_profiles where id = student and organization_id = p_organization_id;
  if previous is null then
    return jsonb_build_object('ok', false, 'message', 'That student profile was not found.');
  end if;
  if private.normalized_matric(previous) is distinct from private.normalized_matric(supplied_matric) and exists (
    select 1 from public.school_profiles sp
    where sp.organization_id = p_organization_id and sp.id <> student
      and private.normalized_matric(sp.matric_number) = private.normalized_matric(supplied_matric)
  ) then
    return jsonb_build_object('ok', false, 'message', 'Another student already uses that matriculation number.');
  end if;

  update public.people set full_name = clean_name, updated_at = clock_timestamp()
  where id = student and organization_id = p_organization_id;

  if private.normalized_matric(previous) = private.normalized_matric(supplied_matric) then
    update public.school_profiles
    set level = clean_level, department_id = department,
        phone = nullif(btrim(coalesce(p_payload->>'phone', '')), '')
    where id = student and organization_id = p_organization_id;
    return jsonb_build_object('ok', true, 'matric_number', previous, 'message', 'Student details updated. The matriculation number was not changed.');
  end if;

  perform set_config('turnmark.allow_matric_correction', 'on', true);
  update public.school_profiles
  set matric_number = supplied_matric, level = clean_level, department_id = department,
      phone = nullif(btrim(coalesce(p_payload->>'phone', '')), '')
  where id = student and organization_id = p_organization_id;
  return jsonb_build_object('ok', true, 'matric_number', supplied_matric, 'message', 'The matriculation number was corrected to the institution-issued value supplied by an administrator.');
exception when unique_violation then
  return jsonb_build_object('ok', false, 'message', 'Another student already uses that matriculation number.');
end $$;

create or replace function public.school_import_roster(p_organization_id uuid, p_course_id uuid, p_students jsonb)
returns jsonb language plpgsql security definer set search_path = '' as $$
declare item jsonb; person uuid; department uuid; full_name text; matric text; inserted_count integer := 0; existing_count integer := 0;
begin
  if private.school_lock_course(p_course_id) is distinct from p_organization_id then raise exception 'Course unavailable' using errcode = '42501'; end if;
  if jsonb_typeof(p_students) is distinct from 'array' or jsonb_array_length(p_students) not between 1 and 500 then raise exception 'Provide 1 to 500 students' using errcode = '22023'; end if;
  select department_id into department from public.courses where id = p_course_id and organization_id = p_organization_id;
  for item in select value from jsonb_array_elements(p_students) loop
    full_name := btrim(item->>'full_name');
    matric := btrim(item->>'matric_number');
    if length(full_name) not between 1 and 160 or length(matric) not between 1 and 80 then raise exception 'Invalid roster row' using errcode = '22023'; end if;
    perform pg_advisory_xact_lock(hashtextextended(p_organization_id::text || ':' || private.normalized_matric(matric), 7));
    select sp.id into person from public.school_profiles sp
    where sp.organization_id = p_organization_id
      and private.normalized_matric(sp.matric_number) = private.normalized_matric(matric)
    for update;
    if person is null then
      insert into public.people(organization_id, type, full_name) values (p_organization_id, 'STUDENT', full_name) returning id into person;
      insert into public.school_profiles(id, organization_id, department_id, matric_number, level)
      values (person, p_organization_id, department, matric, 'UNSPECIFIED');
    elsif not exists(select 1 from public.people p where p.id = person and private.normalized_student_name(p.full_name) = private.normalized_student_name(full_name)) then
      raise exception 'Existing student name does not match roster' using errcode = '22023';
    end if;
    -- An existing profile is enrolled as-is. Its matriculation number is not updated.
    insert into public.course_students(organization_id, course_id, student_id) values (p_organization_id, p_course_id, person) on conflict do nothing;
    if found then inserted_count := inserted_count + 1; else existing_count := existing_count + 1; end if;
  end loop;
  insert into public.business_events(business_id, type, actor_user_id, metadata)
  values (p_organization_id, 'school_enroll', private.current_clerk_user_id(), jsonb_build_object('course_id', p_course_id, 'added', inserted_count, 'existing', existing_count));
  perform private.school_broadcast(p_organization_id, null);
  return jsonb_build_object('added', inserted_count, 'existing', existing_count, 'message', inserted_count || ' students added.');
end $$;

create or replace function public.school_matric_reconciliation(p_organization_id uuid)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare result jsonb;
begin
  if private.current_clerk_user_id() is null or not private.school_manager(p_organization_id) then
    raise exception 'Not authorized' using errcode = '42501';
  end if;
  select jsonb_build_object(
    'organization_id', p_organization_id,
    'student_profiles', (select count(*) from public.school_profiles where organization_id = p_organization_id),
    'normalized_duplicate_groups', (
      select count(*) from (
        select 1 from public.school_profiles
        where organization_id = p_organization_id
        group by private.normalized_matric(matric_number)
        having count(*) > 1
      ) duplicates
    ),
    'attendance_matric_mismatches', (
      select count(*) from public.attendance_records ar
      join public.school_profiles sp on sp.id = ar.student_id
      where ar.organization_id = p_organization_id
        and ar.submitted_matric_number is not null
        and private.normalized_matric(ar.submitted_matric_number) is distinct from private.normalized_matric(sp.matric_number)
    ),
    'sample_mismatches', coalesce((
      select jsonb_agg(sampled.row_data) from (
        select jsonb_build_object(
          'student_id', sp.id,
          'registered_matric', sp.matric_number,
          'submitted_matric', ar.submitted_matric_number,
          'attendance_id', ar.id
        ) as row_data
        from public.attendance_records ar
        join public.school_profiles sp on sp.id = ar.student_id
        where ar.organization_id = p_organization_id
          and ar.submitted_matric_number is not null
          and private.normalized_matric(ar.submitted_matric_number) is distinct from private.normalized_matric(sp.matric_number)
        order by ar.check_in_at desc nulls last
        limit 25
      ) sampled
    ), '[]'::jsonb),
    'rows_rewritten', 0,
    'automatic_merge', false,
    'note', 'This report does not change student records. Matriculation numbers that were uppercased when they were first saved cannot be restored without an external institution source. Do not guess original numbers.'
  ) into result;
  return result;
end $$;

revoke all on function public.school_matric_reconciliation(uuid) from public, anon, authenticated, service_role;
grant execute on function public.school_matric_reconciliation(uuid) to authenticated;

CREATE OR REPLACE FUNCTION public.school_attend_accountless(p_organization_id uuid, p_class_id uuid, p_nonce uuid, p_full_name text, p_matric_number text, p_device_hash text, p_network_hash text, p_request_id uuid, p_photo_url text DEFAULT NULL::text, p_location_lat double precision DEFAULT NULL::double precision, p_location_lng double precision DEFAULT NULL::double precision, p_location_accuracy_meters double precision DEFAULT NULL::double precision, p_location_captured_at timestamp with time zone DEFAULT NULL::timestamp with time zone)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO ''
AS $function$
declare
 cls public.class_sessions%rowtype;
 person uuid;
 canonical_name text;
 canonical_matric text;
 now_at timestamptz:=clock_timestamp();
 st public.attendance_status;
 result jsonb;
 prior public.attendance_scan_requests%rowtype;
 matric_key text;
 outcome text;
 risk text[]:='{}';
 shared uuid;
 clean_name text:=btrim(p_full_name);
 clean_matric text:=btrim(p_matric_number);
 loc jsonb;
 loc_verified boolean:=false;
 captured_at timestamptz;
begin
 perform set_config('turnmark.block_student_create', 'on', true);
 if p_request_id is null or p_nonce is null or p_device_hash is null or p_network_hash is null or length(clean_name) not between 1 and 160
    or length(clean_matric) not between 1 and 80
    or p_device_hash !~ '^[0-9a-f]{64}$' or p_network_hash !~ '^[0-9a-f]{64}$'
 then raise exception 'Invalid attendance request' using errcode='22023'; end if;

 select cs.* into cls from public.class_sessions cs
 where cs.id=p_class_id and cs.organization_id=p_organization_id;
 if not found then raise exception 'Class unavailable' using errcode='42501'; end if;

 matric_key:=encode(extensions.digest(convert_to(p_organization_id::text||':'||private.normalized_matric(clean_matric),'UTF8'),'sha256'),'hex');
 select r.* into prior from public.attendance_scan_requests r
 join public.school_profiles sp on sp.id=r.student_id
 where r.class_session_id=p_class_id and r.request_id=p_request_id and r.nonce=p_nonce
 and private.normalized_matric(sp.matric_number)=private.normalized_matric(clean_matric);
 if found then return prior.result; end if;

 if (select count(*) from public.attendance_submission_limits where class_session_id=p_class_id and device_hash=p_device_hash and created_at>now_at-interval '10 minutes')>=20
    or (select count(*) from public.attendance_submission_limits where class_session_id=p_class_id and matric_hash=matric_key and created_at>now_at-interval '10 minutes')>=10
    or (select count(*) from public.attendance_submission_limits where class_session_id=p_class_id and network_hash=p_network_hash and created_at>now_at-interval '10 minutes')>=300 then
  insert into public.attendance_submission_limits(organization_id,class_session_id,device_hash,network_hash,matric_hash,outcome)
  values(p_organization_id,p_class_id,p_device_hash,p_network_hash,matric_key,'RATE_LIMITED');
  return jsonb_build_object('ok',false,'status','RATE_LIMITED','message','Too many attempts. Wait a moment or ask your lecturer for help.');
 end if;

 if not exists(select 1 from public.attendance_qr_nonces where nonce=p_nonce and organization_id=p_organization_id and class_session_id=p_class_id and expires_at>now_at)
    or cls.qr_revoked_at is not null or not cls.arrival_open
    or not exists(select 1 from public.sessions where id=p_class_id and status='OPEN')
    or (cls.attendance_closes_at is not null and cls.attendance_closes_at<=now_at) then
  insert into public.attendance_submission_limits(organization_id,class_session_id,device_hash,network_hash,matric_hash,outcome)
  values(p_organization_id,p_class_id,p_device_hash,p_network_hash,matric_key,'CLOSED');
  return jsonb_build_object('ok',false,'status','CLOSED','message','Attendance for this class is closed.');
 end if;

 loc := private.school_location_assessment(cls.location_lat, cls.location_lng, cls.geofence_radius_meters, p_location_lat, p_location_lng, p_location_accuracy_meters);
 if cls.location_lat is not null and cls.location_lng is not null and (loc->>'status') is distinct from 'WITHIN_RADIUS' then
  return jsonb_build_object('ok',false,'status',loc->>'status','message',loc->>'message','location_verified',false);
 end if;
 loc_verified := coalesce((loc->>'verified')::boolean, false);
 captured_at := case
  when (loc->>'status') in ('WITHIN_RADIUS','CAPTURED')
    and p_location_captured_at is not null
    and p_location_captured_at <= clock_timestamp() + interval '2 minutes'
    and p_location_captured_at >= clock_timestamp() - interval '15 minutes'
  then p_location_captured_at else clock_timestamp()
 end;

 if cls.verification_mode='VERIFIED' then
  select p.id,p.full_name,sp.matric_number into person,canonical_name,canonical_matric
  from public.class_roster r
  join public.school_profiles sp on sp.id=r.student_id
  join public.people p on p.id=r.student_id
  where r.class_session_id=p_class_id
    and private.normalized_matric(sp.matric_number)=private.normalized_matric(clean_matric);

  if person is null then
   select p.id,p.full_name,sp.matric_number into person,canonical_name,canonical_matric
   from public.course_students cs
   join public.school_profiles sp on sp.id=cs.student_id
   join public.people p on p.id=cs.student_id
   where cs.course_id=cls.course_id and cs.organization_id=p_organization_id
     and private.normalized_matric(sp.matric_number)=private.normalized_matric(clean_matric);
  end if;

  if person is null then
   insert into public.attendance_submission_limits(organization_id,class_session_id,device_hash,network_hash,matric_hash,outcome)
   values(p_organization_id,p_class_id,p_device_hash,p_network_hash,matric_key,'NOT_REGISTERED');
   return jsonb_build_object('ok',false,'status','NOT_REGISTERED','message','Student not found in this course roster. Please contact your lecturer.');
  end if;

  if private.normalized_student_name(canonical_name)<>private.normalized_student_name(clean_name) then
   return jsonb_build_object('ok',false,'status','NAME_MISMATCH','message','The name entered does not match the official course roster.');
  end if;
 else
  perform pg_advisory_xact_lock(hashtextextended(p_organization_id::text||':'||private.normalized_matric(clean_matric),2));
  select p.id,p.full_name,sp.matric_number into person,canonical_name,canonical_matric
  from public.people p join public.school_profiles sp on sp.id=p.id and sp.organization_id=p.organization_id
  where p.organization_id=p_organization_id and p.type='STUDENT'
    and private.normalized_matric(sp.matric_number)=private.normalized_matric(clean_matric)
  for update of p,sp;

  if person is null then
   insert into public.attendance_submission_limits(organization_id,class_session_id,device_hash,network_hash,matric_hash,outcome)
   values(p_organization_id,p_class_id,p_device_hash,p_network_hash,matric_key,'NOT_REGISTERED');
   return jsonb_build_object('ok',false,'status','NOT_REGISTERED','message','That matriculation number is not registered at this institution. Register once with the number your institution issued. Attendance was not recorded and no new number was assigned.');
  elsif private.normalized_student_name(canonical_name)<>private.normalized_student_name(clean_name) then
   return jsonb_build_object('ok',false,'status','IDENTITY_MISMATCH','message','That matric number is already associated with a different name. Please check your details.');
  end if;
  insert into public.course_students(organization_id,course_id,student_id)
  values(p_organization_id,cls.course_id,person) on conflict do nothing;
  insert into public.class_roster(organization_id,class_session_id,student_id)
  values(p_organization_id,p_class_id,person) on conflict do nothing;
 end if;

 -- Atomic duplicate prevention
 perform pg_advisory_xact_lock(hashtextextended(p_class_id::text||':'||person::text,0));
 select * into prior from public.attendance_scan_requests where class_session_id=p_class_id and student_id=person and request_id=p_request_id;
 if found then return prior.result; end if;

 if exists(select 1 from public.attendance_records where class_session_id=p_class_id and student_id=person) then
  result:=jsonb_build_object('ok',false,'status','DUPLICATE','message','Already recorded. Your attendance cannot be submitted twice.');
  outcome:='DUPLICATE';
 else
  if cls.verification_mode='VERIFIED' then
   if exists(select 1 from public.attendance_device_uses where class_session_id=p_class_id and device_hash=p_device_hash and student_id<>person) then risk:=array_append(risk,'POSSIBLE_PROXY_ATTENDANCE'); end if;
  end if;
  now_at:=clock_timestamp();
  st:=case when now_at>(select starts_at from public.sessions where id=p_class_id)+make_interval(mins=>cls.late_after_minutes)
    then 'LATE'::public.attendance_status else 'PRESENT'::public.attendance_status end;

  insert into public.attendance_records(
   organization_id,class_session_id,student_id,check_in_at,status,
   submitted_name,submitted_matric_number,risk_flags,flag_reason,
   photo_url,location_lat,location_lng,location_accuracy_meters,location_verified,location_captured_at,location_distance_meters,location_status,verification_mode
  ) values(
   p_organization_id,p_class_id,person,now_at,st,
   canonical_name,canonical_matric,risk,case when cardinality(risk)>0 then array_to_string(risk,',') end,
   p_photo_url,
   case when (loc->>'status') in ('WITHIN_RADIUS','CAPTURED') then p_location_lat else null end,
   case when (loc->>'status') in ('WITHIN_RADIUS','CAPTURED') then p_location_lng else null end,
   case when (loc->>'status') in ('WITHIN_RADIUS','CAPTURED') then p_location_accuracy_meters else null end,
   loc_verified,
   case when (loc->>'status') in ('WITHIN_RADIUS','CAPTURED') then captured_at else null end,
   (loc->>'distance_meters')::double precision,
   loc->>'status',
   cls.verification_mode
  );

  insert into public.registered_devices(organization_id,student_id,device_hash)
  values(p_organization_id,person,p_device_hash) on conflict(organization_id,student_id,device_hash) do update set last_seen_at=now_at;
  insert into public.attendance_device_uses(organization_id,class_session_id,student_id,device_hash)
  values(p_organization_id,p_class_id,person,p_device_hash) on conflict do nothing;

  if cardinality(risk)>0 then
   for shared in select distinct student_id from public.attendance_device_uses
    where class_session_id=p_class_id and device_hash=p_device_hash and student_id<>person loop
    insert into public.attendance_flags(organization_id,class_session_id,student_id,reason)
    values(p_organization_id,p_class_id,person,'POSSIBLE_PROXY_ATTENDANCE'),
          (p_organization_id,p_class_id,shared,'POSSIBLE_PROXY_ATTENDANCE') on conflict do nothing;
   end loop;
  end if;

  insert into public.presence_events(organization_id,session_id,subject_id,event_type,actor_type,actor_id)
  values(p_organization_id,p_class_id,person,'CHECKED_IN','student',person::text),
        (p_organization_id,p_class_id,person,'ARRIVED','student',person::text);

  result:=jsonb_build_object(
    'ok',true,'status',st,'message','Attendance recorded. '||coalesce(loc->>'message', case when cls.location_lat is null then 'Location was not required for this session.' else '' end),
    'full_name',canonical_name,'matric_number',canonical_matric,
    'course_code',(select c.code from public.courses c where c.id=cls.course_id),
    'photo_url',p_photo_url,
    'recorded_at',now_at,'needs_review',cardinality(risk)>0,
    'identity_status',case when cls.verification_mode='VERIFIED' then 'STUDENT_FOUND' else 'STANDARD' end,
    'location_verified',loc_verified,
    'location_status',loc->>'status'
  );
  outcome:='ACCEPTED';
 end if;

 insert into public.attendance_scan_requests(organization_id,class_session_id,student_id,request_id,nonce,result)
 values(p_organization_id,p_class_id,person,p_request_id,p_nonce,result);
 insert into public.attendance_submission_limits(organization_id,class_session_id,device_hash,network_hash,matric_hash,outcome)
 values(p_organization_id,p_class_id,p_device_hash,p_network_hash,matric_key,outcome);
 perform private.school_broadcast_class(p_organization_id,p_class_id);
 return result;
end $function$;

create or replace function public.school_scan_open(
  p_organization_id uuid,
  p_class_id uuid,
  p_nonce uuid,
  p_full_name text,
  p_matric_number text,
  p_device_hash text,
  p_request_id uuid
) returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  cls public.class_sessions%rowtype;
  course_row public.courses%rowtype;
  person uuid;
  existing_name text;
  rec public.attendance_records%rowtype;
  previous public.attendance_scan_requests%rowtype;
  result jsonb;
  event_name text;
  now_at timestamptz;
  st public.attendance_status;
  shared record;
  clean_name text := btrim(p_full_name);
  clean_matric text := btrim(p_matric_number);
begin
  perform set_config('turnmark.block_student_create', 'on', true);
  perform 1 from public.businesses where id=p_organization_id for share;
  if not private.school_enabled(p_organization_id) then raise exception 'Class unavailable' using errcode='42501'; end if;
  if p_request_id is null or p_nonce is null
    or length(clean_name) not between 1 and 160
    or length(clean_matric) not between 1 and 80
    or p_device_hash is null or p_device_hash !~ '^[0-9a-f]{64}$'
  then raise exception 'Invalid attendance request' using errcode='22023'; end if;

  select * into cls from public.class_sessions
  where id=p_class_id and organization_id=p_organization_id for update;
  if not found then raise exception 'Class unavailable' using errcode='42501'; end if;

  select * into course_row from public.courses
  where id=cls.course_id and organization_id=p_organization_id;
  if not found then raise exception 'Course unavailable' using errcode='42501'; end if;

  select p.id,p.full_name into person,existing_name
  from public.people p
  join public.school_profiles sp on sp.id=p.id and sp.organization_id=p.organization_id
  where p.organization_id=p_organization_id
    and private.normalized_matric(sp.matric_number)=private.normalized_matric(clean_matric)
    and p.type='STUDENT'
  for update of p,sp;

  if found then
    if lower(regexp_replace(btrim(existing_name),'\s+',' ','g'))
       <> lower(regexp_replace(clean_name,'\s+',' ','g')) then
      return jsonb_build_object(
        'ok',false,'action','BLOCKED','status','IDENTITY_MISMATCH',
        'message','That matric number is already registered to a different name. Check your details or ask the lecturer for help.'
      );
    end if;
  else
    return jsonb_build_object(
      'ok',false,'action','BLOCKED','status','NOT_REGISTERED',
      'message','That matriculation number is not registered. Use the number issued by your institution. No new number was assigned.'
    );
  end if;

  insert into public.course_students(organization_id,course_id,student_id)
  values(p_organization_id,cls.course_id,person)
  on conflict(course_id,student_id) do nothing;

  insert into public.class_roster(organization_id,class_session_id,student_id)
  values(p_organization_id,p_class_id,person)
  on conflict(class_session_id,student_id) do nothing;

  now_at:=clock_timestamp();

  select * into previous from public.attendance_scan_requests
  where class_session_id=p_class_id and student_id=person and request_id=p_request_id;
  if found then
    if previous.nonce<>p_nonce then raise exception 'Retry must use the original QR' using errcode='22023'; end if;
    return previous.result;
  end if;

  if (select count(*) from public.attendance_scan_requests
      where class_session_id=p_class_id and student_id=person
        and created_at>now_at-interval '10 minutes')>=60 then
    return jsonb_build_object('ok',false,'action','BLOCKED','status','RATE_LIMITED','message','Too many scans. Please ask your lecturer for help.');
  end if;

  <<transition>> begin
    if not exists(
      select 1 from public.attendance_qr_nonces
      where nonce=p_nonce and organization_id=p_organization_id
        and class_session_id=p_class_id and expires_at>clock_timestamp()
    ) then
      event_name:='INVALID_SCAN';
      result:=jsonb_build_object('ok',false,'action','BLOCKED','status','INVALID_QR','message','This QR has expired or belongs to a different class. Scan the current display.');
      exit transition;
    end if;

    if not exists(select 1 from public.sessions where id=p_class_id and status='OPEN') then
      event_name:='INVALID_SCAN';
      result:=jsonb_build_object('ok',false,'action','BLOCKED','status','CLOSED','message','Attendance is closed.');
      exit transition;
    end if;

    if exists(select 1 from public.attendance_scan_requests
      where class_session_id=p_class_id and student_id=person and nonce=p_nonce) then
      event_name:='DUPLICATE_SCAN';
      result:=jsonb_build_object('ok',false,'action','BLOCKED','status','DUPLICATE_SCAN','message','This scan was already recorded. For departure, scan a new QR after checkout opens.');
      exit transition;
    end if;

    select * into rec from public.attendance_records
    where class_session_id=p_class_id and student_id=person;

    if rec.check_out_at is not null then
      event_name:='DUPLICATE_SCAN';
      insert into public.attendance_flags(organization_id,class_session_id,student_id,reason)
      values(p_organization_id,p_class_id,person,'THIRD_SCAN')
      on conflict do nothing;
      result:=jsonb_build_object('ok',false,'action','BLOCKED','status','THIRD_SCAN','message','Arrival and departure are already recorded. Another scan has been flagged for review.');
      exit transition;
    end if;

    if rec.check_in_at is null then
      if not cls.arrival_open then
        event_name:='INVALID_SCAN';
        result:=jsonb_build_object('ok',false,'action','BLOCKED','status','ARRIVAL_CLOSED','message','Arrival is closed. Please speak to your lecturer.');
        exit transition;
      end if;
      st:=case
        when now_at>(select starts_at from public.sessions where id=p_class_id)+make_interval(mins=>cls.late_after_minutes)
          then 'LATE'::public.attendance_status
        else 'PRESENT'::public.attendance_status
      end;
      insert into public.attendance_records(organization_id,class_session_id,student_id,check_in_at,status)
      values(p_organization_id,p_class_id,person,now_at,st);
      event_name:='CHECKED_IN';
      result:=jsonb_build_object('ok',true,'action','CHECK_IN','status',st,'message','Attendance recorded.');
    else
      if not cls.checkout_enabled then
        event_name:='INVALID_SCAN';
        result:=jsonb_build_object('ok',false,'action','BLOCKED','status','CHECKOUT_CLOSED','message','Your arrival is recorded. Departure scanning is not open yet.');
        exit transition;
      end if;
      st:=case
        when cls.planned_ends_at is not null and now_at<cls.planned_ends_at
          then 'EARLY_LEAVE'::public.attendance_status
        else rec.status
      end;
      update public.attendance_records
      set check_out_at=now_at,status=st,updated_at=now_at where id=rec.id;
      event_name:='CHECKED_OUT';
      result:=jsonb_build_object('ok',true,'action','CHECK_OUT','status',st,'message','Departure recorded.');
    end if;

    insert into public.registered_devices(organization_id,student_id,device_hash)
    values(p_organization_id,person,p_device_hash)
    on conflict(organization_id,student_id,device_hash)
    do update set last_seen_at=now_at;

    insert into public.attendance_device_uses(organization_id,class_session_id,student_id,device_hash)
    values(p_organization_id,p_class_id,person,p_device_hash)
    on conflict do nothing;

    for shared in select distinct student_id
      from public.attendance_device_uses
      where class_session_id=p_class_id and device_hash=p_device_hash and student_id<>person
    loop
      insert into public.attendance_flags(organization_id,class_session_id,student_id,reason)
      values
        (p_organization_id,p_class_id,person,'POSSIBLE_PROXY_ATTENDANCE'),
        (p_organization_id,p_class_id,shared.student_id,'POSSIBLE_PROXY_ATTENDANCE')
      on conflict do nothing;
    end loop;
  end transition;

  insert into public.attendance_scan_requests(organization_id,class_session_id,student_id,request_id,nonce,result)
  values(p_organization_id,p_class_id,person,p_request_id,p_nonce,result);

  insert into public.presence_events(organization_id,session_id,subject_id,event_type,actor_type,actor_id,metadata)
  values(p_organization_id,p_class_id,person,event_name,'student',null,jsonb_build_object('source','qr_self_registration'));

  perform private.school_broadcast(p_organization_id,p_class_id);
  return result;
end
$$;

commit;
